export const PLANT_BY_ID: Record<string, Plant> = Object.fromEntries(PLANTS.map((p) => [p.id, p]));

export function searchPlants(query: string): Plant[] {
  const q = query.trim().toLowerCase();
  if (!q) return PLANTS;
  return PLANTS.filter(
    (p) =>
      p.commonName.toLowerCase().includes(q) ||
      p.scientificName.toLowerCase().includes(q) ||
      p.regionLabel.toLowerCase().includes(q) ||
      p.nativeRegion.toLowerCase().includes(q),
  );
}
